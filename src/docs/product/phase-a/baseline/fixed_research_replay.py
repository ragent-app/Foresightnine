"""Bounded deterministic historical research replay; not a general agent.

Run ``python fixed_research_replay.py initial`` and then ``... update``.
No network, model, external commands, or production data are used.
Existing output records are never overwritten.
"""
import argparse
import datetime
import hashlib
import json
import time
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCRIPT_SHA = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def read_json(name):
    content = (ROOT / name).read_bytes()
    return json.loads(content), hashlib.sha256(content).hexdigest()


def pct(num, den):
    if den <= 0:
        raise ValueError("positive denominator required; no growth/margin calculated")
    return str((Decimal(num) * 100 / Decimal(den)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def validate(source, expected_as_of):
    if source.get("kind") != "derived_facts_not_original_document" or source.get("unit") != "USD millions":
        raise ValueError("unsupported snapshot or unit")
    if source.get("as_of") != expected_as_of or not source.get("source"):
        raise ValueError("unexpected snapshot cutoff or absent source")


def initial():
    stats, stats_hash = read_json("msft-fy2023.json")
    details, details_hash = read_json("msft-2023-details.json")
    validate(stats, "2023-08-01T00:00:00Z")
    validate(details, "2023-08-01T00:00:00Z")
    rev, op = stats["revenue"], stats["operating_income"]
    if details["facts"]["total_revenue"] != rev:
        raise ValueError("2023 income statement revenue snapshots disagree")
    seg = details["facts"]["more_personal_computing_revenue"]
    return {"as_of":stats["as_of"], "stage":"initial", "unit":stats["unit"],
            "sources":[{"url":stats["source"],"location":"Income Statements", "snapshot_sha256":stats_hash},
                       {"url":details["source"],"location":"Segment Results of Operations", "snapshot_sha256":details_hash}],
            "facts":{"revenue_2022":rev["2022"],"revenue_2023":rev["2023"],
                     "operating_income_2023":op["2023"],"segment_revenue_2022":seg["2022"],"segment_revenue_2023":seg["2023"]},
            "calculations":{"revenue_growth":{"formula":"(2023 revenue - 2022 revenue) / 2022 revenue * 100", "percent":pct(rev["2023"]-rev["2022"],rev["2022"])},
                            "operating_margin":{"formula":"2023 operating income / 2023 revenue * 100", "percent":pct(op["2023"],rev["2023"])},
                            "segment_revenue_change":{"formula":"2023 segment revenue - 2022 segment revenue", "value":seg["2023"]-seg["2022"]}},
            "claims":["FY2023 total revenue increased relative to FY2022."],
            "counter_evidence":["More Personal Computing revenue decreased over the same fiscal years; total growth does not imply every segment grew."],
            "unknowns":["No forecast, valuation, share-price conclusion, or complete assessment of drivers is supported by these inputs.",
                        "Source permissions, original-document history and independent human review remain unresolved."],
            "status":"provisional; source extraction and human review pending"}


def update():
    previous, previous_hash = read_json("fixed-research-initial-2026-11-11.json")
    if previous.get("stage") != "initial" or previous.get("script_sha256") != SCRIPT_SHA:
        raise ValueError("initial result missing, wrong stage or generated by another script version")
    source, source_hash = read_json("msft-fy2024.json")
    validate(source, "2024-08-01T00:00:00Z")
    rev, op = source["revenue"], source["operating_income"]
    prior = previous["facts"]
    if rev["2023"] != prior["revenue_2023"] or op["2023"] != prior["operating_income_2023"]:
        raise ValueError("prior-year figures differ; stop and review instead of silently overwriting")
    return {"as_of":source["as_of"],"stage":"update","unit":source["unit"],
            "source":{"url":source["source"],"location":"Income Statements","snapshot_sha256":source_hash},
            "previous_result_sha256":previous_hash,
            "facts":{"revenue_2023":rev["2023"],"revenue_2024":rev["2024"],"operating_income_2024":op["2024"]},
            "calculations":{"revenue_growth":{"formula":"(2024 revenue - 2023 revenue) / 2023 revenue * 100","percent":pct(rev["2024"]-rev["2023"],rev["2023"])},
                            "operating_margin":{"formula":"2024 operating income / 2024 revenue * 100","percent":pct(op["2024"],rev["2024"])}},
            "changes":["FY2024 total revenue and operating income are newly supplied; FY2023 revenue and operating income match the previous snapshot."],
            "retained_counter_evidence":["The initial FY2023 segment decline remains a historical fact; the provided FY2024 snapshot does not show whether that segment recovered."],
            "unknowns":["No FY2024 segment evidence, assessment of causes, price outlook, or user confirmation is provided.",
                        "This is an offline historical replay and does not demonstrate monitoring or detection."],
            "status":"provisional; source extraction and human review pending"}


def main(stage):
    start = time.perf_counter()
    result = initial() if stage == "initial" else update()
    result.update({"script_sha256":SCRIPT_SHA,"run_at_utc":datetime.datetime.now(datetime.timezone.utc).isoformat(),
                   "elapsed_seconds":round(time.perf_counter()-start,6),"model_calls":0,"network_calls":0,
                   "provider_charge_usd":0,"human_and_infrastructure_cost":"not measured"})
    path = ROOT / f"fixed-research-{stage}-2026-11-11.json"
    with path.open("x") as stream:
        json.dump(result, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    print(json.dumps({"output":str(path),"stage":stage,"elapsed_seconds":result["elapsed_seconds"]},ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("stage", choices=("initial", "update"))
    main(parser.parse_args().stage)
